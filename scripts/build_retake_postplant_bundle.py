def load_jsonl(path: Path) -> list[dict]:
    rows: list[dict] = []
    if not path.exists():
        print(f"WARNING: JSONL not found at {path}")
        return rows
    with path.open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                try:
                    rows.append(json.loads(line))
                except json.JSONDecodeError:
                    pass
    return rows


def detect_team_context(match_obj: dict, player_prefix: tuple[str, ...]) -> dict | None:
    team_id = None
    for player in match_obj.get("players", []):
        if player.get("isObserver"):
            continue
        if player.get("gameName", "").startswith(player_prefix):
            team_id = player.get("teamId")
            break
    if team_id is None:
        return None
    team_players = [
        p for p in match_obj.get("players", [])
        if not p.get("isObserver") and p.get("teamId") == team_id
    ]
    return {"teamId": team_id, "teamPlayers": team_players}


def clean_name(game_name: str, player_prefix: tuple[str, ...]) -> str:
    for pfx in player_prefix:
        if game_name.startswith(pfx):
            return game_name[len(pfx):]
    return game_name


def normalize_xy(map_name: str, x: float, y: float) -> tuple[float, float]:
    t = MAP_TRANSFORMS[map_name]
    if t.get("swap_xy"):
        x, y = y, x
    return (y * t["xMultiplier"] + t["xScalarToAdd"]) * 100, (x * t["yMultiplier"] + t["yScalarToAdd"]) * 100


POST_PLANT_MIN_MS = 10_000
POST_PLANT_MAX_MS = 20_000


def build_postplant_10_20(
    map_name: str,
    matches_by_id: dict,
    selected_maps: list,
    player_prefix: tuple[str, ...],
) -> dict:
    """Build per-site 10-20s post-plant snapshot data for the CT retake JSON."""
    postplant_by_site: dict[str, list] = defaultdict(list)
    sample_meta = {s["matchId"]: s for s in selected_maps}

    for match_id, meta in sample_meta.items():
        match_obj = matches_by_id.get(match_id)
        if not match_obj:
            continue

        context = detect_team_context(match_obj, player_prefix)
        if not context:
            continue

        team_puuids = {p["puuid"] for p in context["teamPlayers"] if p.get("puuid")}
        puuid_to_name = {
            p["puuid"]: clean_name(p.get("gameName", ""), player_prefix)
            for p in context["teamPlayers"]
        }

        rounds_by_site: dict[str, dict[int, dict]] = defaultdict(dict)
        for rr in match_obj.get("roundResults", []):
            plant_time = rr.get("plantRoundTime")
            if not plant_time:
                continue
            planter = rr.get("bombPlanter")
            if not planter or planter in team_puuids:
                continue
            site = str(rr.get("plantSite") or "").upper()
            if site not in ("A", "B", "C"):
                continue
            round_num = rr.get("roundNum")
            snapshots: list[dict] = []
            for stat in rr.get("playerStats", []):
                for kill in stat.get("kills", []):
                    tr = kill.get("timeSinceRoundStartMillis")
                    if tr is None:
                        continue
                    since_plant = tr - plant_time
                    if not (POST_PLANT_MIN_MS <= since_plant <= POST_PLANT_MAX_MS):
                        continue
                    locs = kill.get("playerLocations") or []
                    players_at_snap = []
                    for entry in locs:
                        puuid = entry.get("puuid")
                        if puuid not in team_puuids:
                            continue
                        loc = entry.get("location") or {}
                        x, y = loc.get("x"), loc.get("y")
                        if x is None or y is None:
                            continue
                        nx, ny = normalize_xy(map_name, x, y)
                        players_at_snap.append({
                            "player": puuid_to_name.get(puuid, puuid),
                            "normX": round(nx, 4),
                            "normY": round(ny, 4),
                        })
                    if players_at_snap:
                        snapshots.append({"timeSincePlantMs": since_plant, "players": players_at_snap})
            if not snapshots:
                continue
            snapshots.sort(key=lambda s: s["timeSincePlantMs"])
            if round_num not in rounds_by_site[site]:
                rounds_by_site[site][round_num] = {"roundNum": round_num, "snapshots": snapshots}
            else:
                rounds_by_site[site][round_num]["snapshots"].extend(snapshots)
                rounds_by_site[site][round_num]["snapshots"].sort(key=lambda s: s["timeSincePlantMs"])

        for site, rounds in rounds_by_site.items():
            for rnd in rounds.values():
                rnd["matchId"] = match_id
                rnd["date"] = meta.get("date", "")
                rnd["opponent"] = meta.get("opponent", "")
                rnd["score"] = meta.get("score", "")
                postplant_by_site[site].append(rnd)

    return {site: {"rounds": rounds} for site, rounds in postplant_by_site.items()}


def build_dataset(
    map_name: str,
    side_code: str,
    matches_by_id: dict,
    selected_maps: list,
    player_prefix: tuple[str, ...],
) -> dict:
    sites = MAP_SITES[map_name]
    points_by_site: dict[str, list] = {s: [] for s in sites}
    rounds_by_site: dict[str, set] = {s: set() for s in sites}

    for sample in selected_maps:
        match_id = sample.get("matchId")
        match_obj = matches_by_id.get(match_id)
        if not match_obj:
            print(f"  WARNING: match {match_id} not in JSONL — skipping")
            continue

        context = detect_team_context(match_obj, player_prefix)
        if not context:
            continue

        team_puuids = {p["puuid"] for p in context["teamPlayers"] if p.get("puuid")}
        puuid_to_name = {
            p["puuid"]: clean_name(p.get("gameName", ""), player_prefix)
            for p in context["teamPlayers"]
        }
        sides = get_team_side_per_round(
            SimpleNamespace(round_results=match_obj.get("roundResults", [])), team_puuids
        )

        for rr in match_obj.get("roundResults", []):
            round_num = rr.get("roundNum")
            round_side = sides.get(round_num)

            if side_code == "ct" and round_side != "def":
                continue
            if side_code == "t" and round_side != "atk":
                continue

            planter = rr.get("bombPlanter")
            if not planter:
                continue

            site = str(rr.get("plantSite") or "").upper()
            if site not in sites:
                continue

            team_planted = planter in team_puuids
            if side_code == "ct" and team_planted:
                continue
            if side_code == "t" and not team_planted:
                continue

            plant_snapshot = rr.get("plantPlayerLocations") or []
            if not plant_snapshot:
                continue

            round_key = f"{match_id}|{round_num}"
            round_has_point = False

            for entry in plant_snapshot:
                puuid = entry.get("puuid")
                if puuid not in team_puuids:
                    continue
                location = entry.get("location") or {}
                x, y = location.get("x"), location.get("y")
                if x is None or y is None:
                    continue

                norm_x, norm_y = normalize_xy(map_name, x, y)
                points_by_site[site].append({
                    "site": site,
                    "player": puuid_to_name.get(puuid, puuid),
                    "normX": round(norm_x, 4),
                    "normY": round(norm_y, 4),
                    "roundNum": round_num,
                    "plantRoundTimeMs": rr.get("plantRoundTime"),
                    "date": sample.get("date"),
                    "opponent": sample.get("opponent"),
                    "matchId": match_id,
                    "score": sample.get("score"),
                })
                round_has_point = True

            if round_has_point:
                rounds_by_site[site].add(round_key)

    return {
        "map": map_name,
        "side": side_code,
        "selectedMaps": selected_maps,
        "sites": {
            site: {
                "roundCount": len(rounds_by_site[site]),
                "pointCount": len(points_by_site[site]),
                "points": points_by_site[site],
            }
            for site in sites
        },
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--team", required=True, choices=list(TEAM_CONFIG.keys()))
    args = parser.parse_args()

    cfg = TEAM_CONFIG[args.team]
    prefix = cfg["prefix"]
    player_prefix = cfg["player_prefix"]

    print(f"Loading raw JSONL for {prefix.upper()}...")
    all_matches = load_jsonl(cfg["jsonl"])
    matches_by_id = {
        m["matchInfo"]["matchId"]: m
        for m in all_matches
        if m.get("matchInfo", {}).get("matchId")
    }
    print(f"Loaded {len(matches_by_id)} raw matches.\n")

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    for map_name in cfg["maps"]:
        for side_code in ("ct", "t"):
            if side_code == "ct" and map_name in cfg["skip_ct"]:
                print(f"SKIP {map_name} CT (excluded in config)")
                continue

            analysis_json = ANALYSIS_DIR / f"{prefix}_{map_name.lower()}_ct_early_team_positioning_last3.json"
            if not analysis_json.exists():
                print(f"SKIP {map_name} {side_code.upper()}: missing {analysis_json.name}")
                continue

            analysis = json.loads(analysis_json.read_text(encoding="utf-8"))
            selected_maps = analysis.get("selectedMaps", [])
            if not selected_maps:
                print(f"SKIP {map_name} {side_code.upper()}: no selectedMaps in analysis JSON")
                continue

            print(f"[{map_name} {side_code.upper()}] {len(selected_maps)} matches:")
            for m in selected_maps:
                print(f"  {m['date']} vs {m['opponent']} ({m.get('score', '?')})")

            dataset = build_dataset(map_name, side_code, matches_by_id, selected_maps, player_prefix)

            if side_code == "ct":
                pp = build_postplant_10_20(map_name, matches_by_id, selected_maps, player_prefix)
                dataset["postPlant10_20"] = pp
                pp_rounds = sum(len(v["rounds"]) for v in pp.values())
                print(f"  postPlant10_20: {pp_rounds} rounds across sites {list(pp.keys())}")
                ct_plant_rounds = sum(sd["roundCount"] for sd in dataset["sites"].values())
                if pp_rounds == 0 and ct_plant_rounds > 0:
                    print(f"  WARNING: 0 +10-20s rounds despite {ct_plant_rounds} CT plant rounds — check POST_PLANT_MIN/MAX_MS or raw JSONL completeness")
                filename = f"{prefix}_{map_name.lower()}_ct_retake_positions_last3.json"
            else:
                filename = f"{prefix}_{map_name.lower()}_t_postplant_positions_last3.json"

            output_path = OUTPUT_DIR / filename
            output_path.write_text(json.dumps(dataset, indent=2), encoding="utf-8")

            for site in MAP_SITES[map_name]:
                sd = dataset["sites"][site]
                print(f"  Site {site}: {sd['roundCount']}R / {sd['pointCount']}P")
            print(f"  -> {output_path.name}\n")


if __name__ == "__main__":
    main()
