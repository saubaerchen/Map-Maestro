"""Wire the new-season teams into app.js and index.html.

- TEAMS_CONFIG: replaced with the teams in site_config.TEAMS (players + colours from the site data)
- ACTIVE_TEAMS: the same teams
- map images: Abyss/Summit/Sunset added; DEFENSIVE_MAP_ORDER starts with the Kickoff pool
- data versions bumped; index.html map-control script tags replaced

Usage: python scripts/live/wire_site.py
"""
import datetime
import json
import os
import re
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from site_config import KICKOFF_POOL, PALETTE, PUBLISH_DIR, STANDIN_COLOR, TEAMS, site_jsonl, team_pool  # noqa: E402

STAMP = datetime.datetime.now().strftime("%Y%m%d%H%M")   # unique per run, so browsers never reuse a stale cached file


def team_entry(key, cfg):
    tag, pre = cfg["tag"], cfg["prefix"]
    players, maps = Counter(), Counter()
    for line in open(site_jsonl(pre), encoding="utf-8"):
        d = json.loads(line)
        maps[d["matchInfo"]["map"]] += 1
        for p in d["players"]:
            if p["gameName"].startswith(tag + " "):
                players[p["gameName"][len(tag) + 1:]] += 1
    roster = [p for p in cfg["roster"] if p in players]
    others = [p for p, _ in players.most_common() if p not in roster]
    order = roster + others
    colors = {p: (PALETTE[i] if i < len(PALETTE) else STANDIN_COLOR) for i, p in enumerate(roster)}
    colors.update({p: STANDIN_COLOR for p in others})
    team_maps = [m for m in team_pool(cfg) if maps.get(m)]
    no_data = "    noData:       true,\n" if not team_maps else ""
    return (f"  {key}: {{\n"
            f"    filePrefix:   \"{pre}\",\n"
            f"    mapControl:   typeof {pre}MapControlData !== \"undefined\" ? {pre}MapControlData : {{}},\n"
            f"    statMaps:     {json.dumps(team_maps)},\n"
            f"    retakeMaps:   {json.dumps(team_maps)},\n"
            f"    playerColors: {json.dumps(colors)},\n"
            f"    playerOrder:  {json.dumps(order)},\n"
            f"    displayName:  {json.dumps(cfg['name'], ensure_ascii=False)},\n"
            + no_data +
            f"  }},\n")


def sub_once(pattern, repl, text, flags=re.S):
    new, n = re.subn(pattern, repl, text, count=1, flags=flags)
    if n != 1:
        raise SystemExit(f"pattern not found: {pattern[:60]}")
    return new


def main():
    app_path = os.path.join(PUBLISH_DIR, "app.js")
    app = open(app_path, encoding="utf-8").read()
    entries = "".join(team_entry(k, c) for k, c in TEAMS.items())
    app = sub_once(r"(?:// VCT 2027 Kickoff[^\n]*\n)*const TEAMS_CONFIG = \{\n.*?\n\};\n(?=// Derived)",
                   "// VCT 2027 Kickoff — generated by scripts/live/wire_site.py from data/registry + site_config.py\n"
                   "const TEAMS_CONFIG = {\n" + entries + "};\n", app)
    app = sub_once(r"const ACTIVE_TEAMS = new Set\(\[.*?\]\);",
                   "const ACTIVE_TEAMS = new Set(" + json.dumps(list(TEAMS)) + ");", app)
    for var in ("RETAKE_DATA_VERSION", "AGENTS_DATA_VERSION", "ECONOMY_DATA_VERSION"):
        app = sub_once(rf'const {var} = "[^"]*";', f'const {var} = "{STAMP}";', app)
    app = sub_once(r'const MAP_IMAGE_VERSION = "[^"]*";', f'const MAP_IMAGE_VERSION = "{STAMP}";', app)
    if "Summit:" not in app.split("MAP_IMAGE_ASPECTS")[1][:400]:
        app = sub_once(r"(const MAP_IMAGE_ASPECTS = \{\n)", r"\1    Abyss: 1,\n    Summit: 1,\n    Sunset: 1,\n", app)
        app = sub_once(r"(const MAP_IMAGE_PATHS = \{\n)",
                       "\\1    Abyss: `./maps/Abyss.png?v=${MAP_IMAGE_VERSION}`,\n"
                       "    Summit: `./maps/Summit.png?v=${MAP_IMAGE_VERSION}`,\n"
                       "    Sunset: `./maps/Sunset.png?v=${MAP_IMAGE_VERSION}`,\n", app)
    app = sub_once(r"const DEFENSIVE_MAP_ORDER = \[.*?\];",
                   "const DEFENSIVE_MAP_ORDER = " + json.dumps(KICKOFF_POOL + ["Ascent", "Split", "Breeze", "Pearl", "Fracture", "Icebox"]) + ";", app)
    open(app_path, "w", encoding="utf-8").write(app)

    idx_path = os.path.join(PUBLISH_DIR, "index.html")
    idx = open(idx_path, encoding="utf-8").read()
    lines = idx.split("\n")
    out, inserted = [], False
    for ln in lines:
        if re.search(r'<script src="\./[a-z0-9]*-?map-control-data\.js', ln):
            if not inserted:
                indent = re.match(r"\s*", ln).group(0)
                for cfg in TEAMS.values():
                    sj = site_jsonl(cfg["prefix"])
                    if not os.path.exists(sj) or os.path.getsize(sj) == 0:
                        continue   # no data this season: never load an old-season map-control file
                    out.append(f'{indent}<script src="./{cfg["prefix"]}-map-control-data.js?v={STAMP}"></script>')
                inserted = True
            continue
        ln = re.sub(r'(src="\./(data|extra-data|defensive-early-data|app)\.js)\?v=[^"]*"', rf'\1?v={STAMP}"', ln)
        out.append(ln)
    open(idx_path, "w", encoding="utf-8").write("\n".join(out))
    print("app.js + index.html wired, version", STAMP)
    print(entries)


if __name__ == "__main__":
    main()
